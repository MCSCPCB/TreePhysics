import { readFile, writeFile } from "node:fs/promises";

const SABLE_DATA = "sample/sable/common/src/main/resources/data/sable";
const OUTPUT = "src/data/generated/block-physics-properties.generated.ts";

const propertySources = [
  {
    file: "physics_block_properties/slippery.json",
    typeIds: [
      "minecraft:blue_ice",
      "minecraft:frosted_ice",
      "minecraft:ice",
      "minecraft:packed_ice"
    ]
  },
  {
    file: "physics_block_properties/sticky.json",
    typeIds: [
      "minecraft:cactus",
      "minecraft:honey_block",
      "minecraft:soul_sand",
      "minecraft:soul_soil"
    ]
  },
  {
    file: "physics_block_properties/bouncy.json",
    typeIds: ["minecraft:slime_block"]
  },
  {
    file: "physics_block_properties/mud.json",
    typeIds: ["minecraft:mud"]
  },
  {
    file: "physics_block_properties/grindstone.json",
    typeIds: ["minecraft:grindstone"]
  }
];

const fragileTypeIds = [
  "minecraft:acacia_leaves",
  "minecraft:azalea_leaves",
  "minecraft:azalea_leaves_flowered",
  "minecraft:bamboo",
  "minecraft:bee_nest",
  "minecraft:birch_leaves",
  "minecraft:cactus",
  "minecraft:cherry_leaves",
  "minecraft:cocoa",
  "minecraft:dark_oak_leaves",
  "minecraft:frosted_ice",
  "minecraft:ice",
  "minecraft:jungle_leaves",
  "minecraft:leaves",
  "minecraft:leaves2",
  "minecraft:lily_pad",
  "minecraft:mangrove_leaves",
  "minecraft:melon_block",
  "minecraft:oak_leaves",
  "minecraft:pale_oak_leaves",
  "minecraft:pumpkin",
  "minecraft:spruce_leaves"
];

// Tree Physics overrides Sable's generic 4 m/s fragile threshold for leaves.
// LeavesBlockCallback.getTriggerVelocity() returns 0 for non-persistent leaves.
const leafTypeIds = fragileTypeIds.filter(typeId =>
  typeId === "minecraft:leaves"
  || typeId === "minecraft:leaves2"
  || typeId.endsWith("_leaves")
  || typeId === "minecraft:azalea_leaves_flowered"
);

const records = new Map();
for (const source of propertySources) {
  const document = JSON.parse(await readFile(`${SABLE_DATA}/${source.file}`, "utf8"));
  const properties = {};
  if (Number.isFinite(document.properties?.["sable:friction"])) {
    properties.friction = document.properties["sable:friction"];
  }
  if (Number.isFinite(document.properties?.["sable:restitution"])) {
    properties.restitution = document.properties["sable:restitution"];
  }
  for (const typeId of source.typeIds) {
    records.set(typeId, { ...(records.get(typeId) ?? {}), ...properties });
  }
}
for (const typeId of fragileTypeIds) {
  records.set(typeId, { ...(records.get(typeId) ?? {}), fragileImpactSpeed: 4 });
}
for (const typeId of leafTypeIds) {
  records.set(typeId, { ...(records.get(typeId) ?? {}), fragileImpactSpeed: 0 });
}

const entries = [...records].sort(([left], [right]) => left.localeCompare(right));
const lines = [
  "// Generated by scripts/generators/block-physics-properties.mjs from Sable reference data.",
  "import type { PhysicsBlockProperties } from \"@src/physics/types\";",
  "",
  "export const BLOCK_PHYSICS_PROPERTIES: Readonly<Record<string, PhysicsBlockProperties>> = {"
];
for (const [typeId, properties] of entries) {
  lines.push(`  ${JSON.stringify(typeId)}: ${JSON.stringify(properties)},`);
}
lines.push("};", "");
await writeFile(OUTPUT, lines.join("\n"));
console.log(`Generated ${entries.length} block physics property records from Sable reference data.`);
