import { readFile, writeFile } from "node:fs/promises";

const blocks = JSON.parse(await readFile("sample/vanilla-sound/blocks.json", "utf8"));
const sounds = JSON.parse(await readFile("sample/vanilla-sound/sounds.json", "utf8"));
const blockSounds = sounds.block_sounds ?? {};
const interactiveBlockSounds = sounds.interactive_sounds?.block_sounds ?? {};
const breakEventEncoder = createEventEncoder();
const placeEventEncoder = createEventEncoder();
const hitEventEncoder = createEventEncoder();
const stepEventEncoder = createEventEncoder();
const jumpEventEncoder = createEventEncoder();
const landEventEncoder = createEventEncoder();
const fallEventEncoder = createEventEncoder();
const breakEvents = {};
const placeEvents = {};
const treeHitEvents = {};
const treeStepEvents = {};
const treeJumpEvents = {};
const treeLandEvents = {};
const treeFallEvents = {};

for (const [blockName, definition] of Object.entries(blocks)) {
  const soundGroup = definition?.sound;
  const treePhysicsBlock = isTreePhysicsBlock(blockName);
  if (treePhysicsBlock) {
    const hitEvent = resolveSoundEvent(blockSounds, soundGroup, "hit");
    if (hitEvent) treeHitEvents[`minecraft:${blockName}`] = hitEventEncoder.encode(hitEvent);
    const stepEvent = resolveInteractiveSoundEvent(soundGroup, "step");
    if (stepEvent) treeStepEvents[`minecraft:${blockName}`] = stepEventEncoder.encode(stepEvent);
    const jumpEvent = resolveInteractiveSoundEvent(soundGroup, "jump");
    if (jumpEvent) treeJumpEvents[`minecraft:${blockName}`] = jumpEventEncoder.encode(jumpEvent);
    const landEvent = resolveInteractiveSoundEvent(soundGroup, "land");
    if (landEvent) treeLandEvents[`minecraft:${blockName}`] = landEventEncoder.encode(landEvent);
    const fallEvent = resolveInteractiveSoundEvent(soundGroup, "fall");
    if (fallEvent) treeFallEvents[`minecraft:${blockName}`] = fallEventEncoder.encode(fallEvent);
  }
  const breakEvent = resolveSoundEvent(blockSounds, soundGroup, "break");
  if (breakEvent) breakEvents[`minecraft:${blockName}`] = breakEventEncoder.encode(breakEvent);
  const placeEvent = resolveSoundEvent(blockSounds, soundGroup, "place");
  if (placeEvent) placeEvents[`minecraft:${blockName}`] = placeEventEncoder.encode(placeEvent);
}

// These blocks intentionally omit a sound group in the extracted Bedrock table,
// but use the wooden break group in vanilla gameplay.
const woodBreakEvent = requireSoundEvent(blockSounds, "wood", "break");
const woodHitEvent = requireSoundEvent(blockSounds, "wood", "hit");
const woodStepEvent = requireSoundEvent(interactiveBlockSounds, "wood", "step");
const woodJumpEvent = requireSoundEvent(interactiveBlockSounds, "wood", "jump");
const woodLandEvent = requireSoundEvent(interactiveBlockSounds, "wood", "land");
const woodFallEvent = requireSoundEvent(interactiveBlockSounds, "wood", "fall");
breakEvents["minecraft:bee_nest"] ??= breakEventEncoder.encode(woodBreakEvent);
breakEvents["minecraft:beehive"] ??= breakEventEncoder.encode(woodBreakEvent);
treeHitEvents["minecraft:bee_nest"] ??= hitEventEncoder.encode(woodHitEvent);
treeHitEvents["minecraft:beehive"] ??= hitEventEncoder.encode(woodHitEvent);
treeStepEvents["minecraft:bee_nest"] ??= stepEventEncoder.encode(woodStepEvent);
treeStepEvents["minecraft:beehive"] ??= stepEventEncoder.encode(woodStepEvent);
treeJumpEvents["minecraft:bee_nest"] ??= jumpEventEncoder.encode(woodJumpEvent);
treeJumpEvents["minecraft:beehive"] ??= jumpEventEncoder.encode(woodJumpEvent);
treeLandEvents["minecraft:bee_nest"] ??= landEventEncoder.encode(woodLandEvent);
treeLandEvents["minecraft:beehive"] ??= landEventEncoder.encode(woodLandEvent);
treeFallEvents["minecraft:bee_nest"] ??= fallEventEncoder.encode(woodFallEvent);
treeFallEvents["minecraft:beehive"] ??= fallEventEncoder.encode(woodFallEvent);

const output = `// Generated by scripts/generators/vanilla-block-sounds.mjs.\n`
  + `export type GeneratedBlockSoundEvent = readonly `
  + `[sound: string, pitchMin: number, pitchMax: number, volumeMin: number, volumeMax: number];\n\n`
  + `export const VANILLA_BLOCK_BREAK_SOUND_EVENTS: readonly GeneratedBlockSoundEvent[] = `
  + `${JSON.stringify(breakEventEncoder.events, null, 2)};\n\n`
  + `export const VANILLA_BLOCK_BREAK_SOUND_EVENT_INDICES: `
  + `Readonly<Record<string, number>> = `
  + `${JSON.stringify(sortRecord(breakEvents), null, 2)};\n\n`
  + `export const VANILLA_BLOCK_PLACE_SOUND_EVENTS: readonly GeneratedBlockSoundEvent[] = `
  + `${JSON.stringify(placeEventEncoder.events, null, 2)};\n\n`
  + `export const VANILLA_BLOCK_PLACE_SOUND_EVENT_INDICES: `
  + `Readonly<Record<string, number>> = `
  + `${JSON.stringify(sortRecord(placeEvents), null, 2)};\n\n`
  + `export const VANILLA_TREE_HIT_SOUND_EVENTS: readonly GeneratedBlockSoundEvent[] = `
  + `${JSON.stringify(hitEventEncoder.events, null, 2)};\n\n`
  + `export const VANILLA_TREE_HIT_SOUND_EVENT_INDICES: `
  + `Readonly<Record<string, number>> = `
  + `${JSON.stringify(sortRecord(treeHitEvents), null, 2)};\n\n`
  + `export const VANILLA_TREE_STEP_SOUND_EVENTS: readonly GeneratedBlockSoundEvent[] = `
  + `${JSON.stringify(stepEventEncoder.events, null, 2)};\n\n`
  + `export const VANILLA_TREE_STEP_SOUND_EVENT_INDICES: `
  + `Readonly<Record<string, number>> = `
  + `${JSON.stringify(sortRecord(treeStepEvents), null, 2)};\n\n`
  + `export const VANILLA_TREE_JUMP_SOUND_EVENTS: readonly GeneratedBlockSoundEvent[] = `
