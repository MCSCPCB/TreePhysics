function resolveSoundEvent(soundGroups, soundGroup, eventName, visited = new Set()) {
  if (typeof soundGroup !== "string" || visited.has(soundGroup)) return undefined;
  visited.add(soundGroup);
  const definition = soundGroups[soundGroup];
  if (!definition) return undefined;
  const event = definition?.events?.[eventName];
  const sound = typeof event === "string" ? event : event?.sound;
  if (typeof sound === "string" && sound.length > 0) {
    const groupPitch = resolveGroupNumber(soundGroups, soundGroup, "pitch", new Set());
    const groupVolume = resolveGroupNumber(soundGroups, soundGroup, "volume", new Set());
    const [pitchMin, pitchMax] = numberRange(
      typeof event === "string" ? undefined : event.pitch,
      1
    );
    const [volumeMin, volumeMax] = numberRange(
      typeof event === "string" ? undefined : event.volume,
      1
    );
    return {
      pitchMax: pitchMax * groupPitch,
      pitchMin: pitchMin * groupPitch,
      sound,
      volumeMax: volumeMax * groupVolume,
      volumeMin: volumeMin * groupVolume
    };
  }
  return resolveSoundEvent(soundGroups, definition?.base, eventName, visited);
}

function resolveGroupNumber(soundGroups, soundGroup, property, visited) {
  if (typeof soundGroup !== "string" || visited.has(soundGroup)) return 1;
  visited.add(soundGroup);
  const definition = soundGroups[soundGroup];
  const value = definition?.[property];
  if (typeof value === "number") return value;
  return resolveGroupNumber(soundGroups, definition?.base, property, visited);
}

function requireSoundEvent(soundGroups, soundGroup, eventName) {
  const event = resolveSoundEvent(soundGroups, soundGroup, eventName);
  if (!event) throw new Error(`Missing ${eventName} sound for group ${soundGroup}.`);
  return event;
}

function resolveInteractiveSoundEvent(soundGroup, eventName) {
  return resolveSoundEvent(interactiveBlockSounds, soundGroup, eventName)
    ?? resolveSoundEvent(interactiveBlockSounds, blockSounds[soundGroup]?.base, eventName);
}

function numberRange(value, fallback) {
  if (typeof value === "number") return [value, value];
  if (
    Array.isArray(value)
    && value.length === 2
    && value.every(entry => typeof entry === "number")
  ) return [Math.min(...value), Math.max(...value)];
  return [fallback, fallback];
}

function createEventEncoder() {
  const events = [];
  const indices = new Map();
  return {
    encode(event) {
      const encoded = [
        event.sound,
        event.pitchMin,
        event.pitchMax,
        event.volumeMin,
        event.volumeMax
      ];
      const key = encoded.join("|");
      const existing = indices.get(key);
      if (existing !== undefined) return existing;
      const index = events.length;
      events.push(encoded);
      indices.set(key, index);
      return index;
    },
    events
  };
}

function sortRecord(record) {
  return Object.fromEntries(Object.entries(record).sort());
}

function isTreePhysicsBlock(blockName) {
  return blockName === "creaking_heart"
    || blockName === "leaves"
    || blockName === "leaves2"
    || blockName === "log"
    || blockName === "log2"
    || blockName === "azalea_leaves_flowered"
    || blockName === "bee_nest"
    || blockName === "cocoa"
    || blockName === "hanging_roots"
    || blockName === "mangrove_propagule"
    || blockName === "mangrove_roots"
    || blockName === "muddy_mangrove_roots"
    || blockName === "pale_hanging_moss"
    || blockName === "vine"
    || blockName.endsWith("_leaves")
    || blockName.endsWith("_log")
    || blockName.endsWith("_wood");
}
